"""Emit the paper's LaTeX table bodies from the stored artefacts.

Every number in paper_cms.tex comes from this script; nothing is hand-typed.
Each table body is written to its own file, paper/tab/<name>.tex, holding one
`tabular` environment. The manuscript wraps each in a float with its caption,
so captions stay in the prose file and numbers stay generated.

Usage: py -3.12 paper/tables.py
"""
import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
M = os.path.join(ROOT, "models")
D = os.path.join(ROOT, "data", "raw")
TAB = os.path.join(ROOT, "paper", "tab")
os.makedirs(TAB, exist_ok=True)

SEEDS = [42, 123, 2024]
SYS = ["fecrni", "fecrmn", "fecrmo", "fecrv", "femnni"]
LBL = {"fecrni": "Fe--Cr--Ni", "fecrmn": "Fe--Cr--Mn", "fecrmo": "Fe--Cr--Mo",
       "fecrv": "Fe--Cr--V", "femnni": "Fe--Mn--Ni"}


def results(system):
    out = {}
    for fn in [f"results_heads_{system}.json", f"results_baselines_{system}.json"]:
        p = os.path.join(M, fn)
        if os.path.exists(p):
            out.update(json.load(open(p)))
    if system == "fecrni":
        p = os.path.join(M, "results_a23.json")
        if os.path.exists(p):
            out.update(json.load(open(p)))
    return out


def agg(d, prefix, field="mean_mae"):
    v = [d[f"{prefix}_s{s}"][field] for s in SEEDS if f"{prefix}_s{s}" in d]
    return (float(np.mean(v)), float(np.std(v)), v) if v else (np.nan, np.nan, [])


def phases(system):
    probe = json.load(open(os.path.join(D, f"{system}_probe.json")))
    names = sorted(probe["active_counts"].keys())
    return names, [f"NP_{p}" for p in names]


def tex_phase(name):
    return name.replace("_", "\\_")


def mae_cell(m, s, bold=False):
    if np.isnan(m):
        return "---"
    # uncertainty in units of the last digit
    txt = f"{m:.4f}\\,({int(round(s * 1e4)):d})"
    return f"\\textbf{{{txt}}}" if bold else txt


def sci(x, digits=1):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "---"
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    mant = x / 10 ** e
    return f"${mant:.{digits}f}\\!\\times\\!10^{{{e}}}$"


L = []
W = L.append


def emit(name):
    """Flush the accumulated lines to paper/tab/<name>.tex."""
    global L, W
    body = [x for x in L if not x.startswith("%") or True]
    with open(os.path.join(TAB, f"{name}.tex"), "w", encoding="utf-8") as f:
        f.write("% Generated by paper/tables.py -- do not edit by hand.\n")
        f.write("\n".join(body).rstrip() + "\n")
    print(f"  wrote tab/{name}.tex")
    L = []
    W = L.append


