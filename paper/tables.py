W(" & Model & " + " & ".join(LBL[s] for s in SYS) + " \\\\")
W("\\midrule")
group = {0: "\\multirow{2}{*}{\\rotatebox{90}{\\scriptsize off-simplex}}",
         1: "\\multirow{5}{*}{\\rotatebox{90}{\\scriptsize on-simplex}}",
         2: "\\multirow{4}{*}{\\rotatebox{90}{\\scriptsize baselines}}"}
seen = set()
for key, lab, g in ROWS:
    if key is None:
        W("\\midrule")
