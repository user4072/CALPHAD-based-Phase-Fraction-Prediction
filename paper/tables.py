def bagg(s, tag, field="mean_mae", src=None):
    d = (src if src is not None else BH).get(s, {})
    v = [d[f"{tag}_s{k}"][field] for k in SEEDS if f"{tag}_s{k}" in d]
    return (float(np.mean(v)), float(np.std(v))) if v else (np.nan, np.nan)


MODELS = [("mlp_renorm", "MLP renorm"), ("mlp_sig_norm", "MLP sigmoid/$\\Sigma$"),
          ("rf_renorm", "random forest"), ("xgb_renorm", "XGBoost")]
if BH:
    W("\\scriptsize")
    W("\\setlength{\\tabcolsep}{3pt}")
    W("\\begin{tabular}{ll" + "c" * len(SYS) + "}")
    W("\\toprule")
    W("Held-out region & Model & " + " & ".join(LBL[s] for s in SYS) + " \\\\")
    W("\\midrule")
    for bi, (blk, blab) in enumerate([("random_ctrl", "random control"),
                                      ("T_band", "$T \\in [1200,1400]$\\,K"),
                                      ("X2_band", "$x_2 \\in [0.25,0.35]$")]):
        for mi, (key, mlab) in enumerate(MODELS):
            cells = []
            for s in SYS:
                m, sd = bagg(s, f"{blk}_{key}")
                cells.append(mae_cell(m, sd))
            tag = f"\\multirow{{4}}{{*}}{{{blab}}}" if mi == 0 else ""
            W(f"{tag} & {mlab} & " + " & ".join(cells) + " \\\\")
        if bi < 2:
            W("\\addlinespace")
    W("\\midrule")
    # degradation ratios relative to the random control
    for key, mlab in MODELS:
        cells = []
        for s in SYS:
            c, _ = bagg(s, f"random_ctrl_{key}")
            t, _ = bagg(s, f"T_band_{key}")
            x, _ = bagg(s, f"X2_band_{key}")
            cells.append("---" if np.isnan(c) else
                         f"{t / c:.2f} / {x / c:.2f}")
        W(f"{'penalty $T$/$x_2$' if key == MODELS[0][0] else ''} & {mlab} & "
          + " & ".join(cells) + " \\\\")
    W("\\bottomrule")
    W("\\end{tabular}")
