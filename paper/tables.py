    tag = group[g] if g not in seen else ""
    seen.add(g)
    cells = []
    for s in SYS:
        m, sd, _ = agg(results(s), key)
        cells.append(mae_cell(m, sd, bold=(best[s] == key)))
    W(f"{tag} & {lab} & " + " & ".join(cells) + " \\\\")
