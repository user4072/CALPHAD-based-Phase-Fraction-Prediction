def jload(path):
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def fmtv(x):
    """Fixed point for O(1) numbers, scientific otherwise."""
    ax = abs(x)
    if ax == 0:
        return "0"
    if ax < 1e-3 or ax >= 1e3:
        return sci(x)
    if ax < 1:
        return f"{x:.2f}"
    return f"{x:.1f}"


